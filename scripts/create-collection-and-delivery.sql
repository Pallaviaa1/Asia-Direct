-- Collection / Delivery edit-form table (matches production structure)
CREATE TABLE IF NOT EXISTS `collection_and_delivery` (
  `id` int(10) UNSIGNED NOT NULL AUTO_INCREMENT,
  `freight_id` int(11) NOT NULL,
  `order_id` int(11) NOT NULL,
  `assign_supplier_id` int(11) DEFAULT NULL,
  `warehouse_number` varchar(50) DEFAULT NULL,
  `supplier_name` varchar(255) DEFAULT NULL,
  `supplier_contact_person` varchar(255) DEFAULT NULL,
  `supplier_contact` varchar(100) DEFAULT NULL,
  `pickup_address` text DEFAULT NULL,
  `customer_ref` varchar(255) DEFAULT NULL,
  `create_new_warehouse_order` enum('Yes','No') DEFAULT 'No',
  `freight_number` varchar(100) DEFAULT NULL,
  `warehouse_order_id` varchar(100) DEFAULT NULL,
  `date_picked_up` date DEFAULT NULL,
  `courier_waybill_ref` varchar(100) DEFAULT NULL,
  `box_marking` text DEFAULT NULL,
  `box_marking_attachment` longtext DEFAULT NULL,
  `goods_description` text DEFAULT NULL,
  `goods_description_attachment` longtext DEFAULT NULL,
  `package_type` varchar(100) DEFAULT NULL,
  `hazardous` enum('Yes','No') DEFAULT 'No',
  `hazardous_description` text DEFAULT NULL,
  `total_packages` int(11) DEFAULT 0,
  `total_cbm` decimal(10,3) DEFAULT 0.000,
  `total_weight` decimal(10,2) DEFAULT 0.00,
  `package_comments` text DEFAULT NULL,
  `costs_to_collect` decimal(10,2) DEFAULT 0.00,
  `handling_cost` decimal(10,2) DEFAULT 0.00,
  `warehouse_cost` decimal(10,2) DEFAULT 0.00,
  `product_pictures` longtext DEFAULT NULL,
  `other_attachments` longtext DEFAULT NULL,
  `warehouse_comment` text DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `warehouse_number` (`warehouse_number`),
  KEY `idx_freight_id` (`freight_id`),
  KEY `idx_freight_number` (`freight_number`),
  KEY `idx_order_id` (`order_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
